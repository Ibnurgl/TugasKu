    public void tampilData() {
    // Membuat struktur kolom tabel
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
    model.addColumn("No");
    model.addColumn("Nama Tugas");
    model.addColumn("Mata Kuliah");
    model.addColumn("Deadline");

    try {
        int no = 1;
        String sql = "SELECT * FROM tugas";
        java.sql.Connection conn = database.Koneksi.getKoneksi(); 
        java.sql.Statement stm = conn.createStatement();
        java.sql.ResultSet res = stm.executeQuery(sql);

        // Memasukkan data dari MySQL baris demi baris ke tabel GUI
        while (res.next()) {
            model.addRow(new Object[]{
                no++,
                res.getString("nama_tugas"),
                res.getString("mata_kuliah"),
                res.getString("deadline")
            });
        }
        
        // Pasang model data ke JTable (sesuaikan 'tblTugas' dengan nama variabel JTable Anda)
        tblTugas.setModel(model); 
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat tabel: " + e.getMessage());
    }
}

