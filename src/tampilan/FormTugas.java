    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed

        try {
        // Cek apakah kolom nama tugas kosong
        if (txtNamaTugas.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog
        (this, "Pilih atau ketik Nama Tugas yang ingin dihapus!");
            return;
        }

        // Memunculkan pop-up konfirmasi
        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog
        (this, "Yakin ingin menghapus tugas ini?", "Konfirmasi", 
                javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM tugas WHERE nama_tugas = ?";
            java.sql.Connection conn = database.Koneksi.getKoneksi();
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            
            // Menghapus berdasarkan teks di txtNamaTugas
            pst.setString(1, txtNamaTugas.getText());
            pst.execute();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Data Tugas Berhasil Dihapus!");
            
            // Kosongkan form dan refresh tabel
            txtNamaTugas.setText("");
            txtDeadline.setText("");
            cbMatkul.setSelectedIndex(0);
            tampilData();
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus: " + e.getMessage());
    }
    }//GEN-LAST:event_btnHapusActionPerformed

